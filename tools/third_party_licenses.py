"""Write THIRD_PARTY_LICENSES.md: every crate linked into the ES 1 plugin, with its license
files.

The permissive licenses of the dependencies (MIT, BSD, ISC, Zlib, Apache-2.0, ...) require their
copyright and license notices to travel with binary copies. This collects the crate's own license
files from Cargo's source cache; identical texts are printed once and referenced. Crates that
ship no license file get the standard text of their declared license.

    python tools/third_party_licenses.py [--target x86_64-pc-windows-msvc]

Run it after changing dependencies (`cargo xtask bundle` copies the result into the bundle).
"""

