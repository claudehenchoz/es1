OUT = ROOT / "THIRD_PARTY_LICENSES.md"
ROOT_CRATE = "es1-vst3"
LICENSE_PREFIXES = ("LICENSE", "LICENCE", "COPYING", "COPYRIGHT", "NOTICE", "UNLICENSE", "AUTHORS")
# Crates that keep license files outside the usual places: {crate name: [paths]}.
