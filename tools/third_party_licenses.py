def metadata(target):
    out = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
        cwd=ROOT, check=True, capture_output=True, text=True, encoding="utf-8",
    ).stdout
    return json.loads(out)


def linked_packages(m):
    """Packages reachable from the plugin through normal (linked) dependencies."""
    pk = {p["id"]: p for p in m["packages"]}
    nodes = {n["id"]: n for n in m["resolve"]["nodes"]}
    ws = set(m["workspace_members"])
    root = next(i for i in ws if pk[i]["name"] == ROOT_CRATE)
    seen, stack = set(), [root]
    while stack:
        i = stack.pop()
        if i in seen:
            continue
        seen.add(i)
        for d in nodes[i]["deps"]:
            if any(k["kind"] is None for k in d["dep_kinds"]):
                stack.append(d["pkg"])
    return sorted((pk[i] for i in seen - ws), key=lambda p: (p["name"].lower(), p["version"]))


def license_files(p):
    d = Path(p["manifest_path"]).parent
    files = [f for f in sorted(d.iterdir()) if f.is_file() and f.name.upper().startswith(LICENSE_PREFIXES)]
    # Members of a git workspace (nih-plug) keep the license at the repository root.
    up = d
    while not files and p["source"] and p["source"].startswith("git+") and (up / "..").resolve() != up:
        up = up.parent
        if not any(up.glob("Cargo.toml")):
            break
        files = [f for f in sorted(up.iterdir()) if f.is_file() and f.name.upper().startswith(LICENSE_PREFIXES)]
    if p.get("license_file"):
        lf = (d / p["license_file"]).resolve()
        if lf.is_file() and lf not in files:
            files.append(lf)
    files += [d / x for x in EXTRA.get(p["name"], []) if (d / x).is_file()]
    return files


def main():
    target = sys.argv[sys.argv.index("--target") + 1] if "--target" in sys.argv else "x86_64-pc-windows-msvc"
    m = metadata(target)
    pkgs = linked_packages(m)
    texts = {}  # sha -> (label, text)
    apache = None
    entries = []
    for p in pkgs:
        refs = []
        for f in license_files(p):
            t = f.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip()
            h = hashlib.sha256(" ".join(t.split()).encode()).hexdigest()[:12]
            texts.setdefault(h, (f.name, t))
            refs.append((f.name, h))
            if apache is None and "Apache License" in t and "Version 2.0" in t and "TERMS AND CONDITIONS" in t:
                apache = h
        entries.append((p, refs))
    for p, refs in entries:
        lic = p.get("license") or ""
        have = " ".join(texts[h][1] for _, h in refs)
        if not refs and "BSL-1.0" in lic:
            refs.append(("BSL-1.0 (standard text)", "bsl"))
        elif "MIT" in lic and "Permission is hereby granted" not in have and not (refs and "OR" in lic and "MIT" not in lic.split("AND")[0]):
            refs.append(("MIT (standard text)", "mit"))
        elif not refs and "Apache-2.0" in lic and apache:
            refs.append(("Apache-2.0 (standard text)", apache))
    lines = [
        "<!-- Generated by tools/third_party_licenses.py; do not edit. -->",
        "",
        "# Third-party licenses",
        "",
        f"ES 1 links the following {len(pkgs)} crates (target `{target}`). Their licenses are",
        "permissive or, in the case of `vst3-sys`, GPL-3.0; all are compatible with ES 1's",
        "GPL-3.0-or-later. Each crate's own license files follow; texts shared by several crates are",
        "printed once at the end and referenced by id.",
        "",
        "| Crate | Version | License | Source | License files |",
        "|---|---|---|---|---|",
    ]
    for p, refs in entries:
        src = p.get("repository") or ""
        if p["source"] is None:  # a path dependency: the patched copy in vendor/
            src += " (modified copy in `vendor/`)"
        files = ", ".join(f"{n} [{h}](#{h})" for n, h in refs) or "(none shipped)"
        lines.append(f"| {p['name']} | {p['version']} | {p.get('license') or ''} | {src} | {files} |")
    lines += ["", "## Copyright holders (from crate metadata)", ""]
    for p, _ in entries:
        authors = ", ".join(a.split(" <")[0] for a in p.get("authors") or []) or "the authors"
        lines.append(f"* {p['name']} {p['version']}: {authors}")
    lines += ["", "## License texts", ""]
    if any(h == "bsl" for _, refs in entries for _, h in refs):
        texts["bsl"] = ("BSL-1.0", BSL)
    if any(h == "mit" for _, refs in entries for _, h in refs):
        texts["mit"] = ("MIT", "Copyright (c) the authors listed above for the crate.\n\n" + MIT)
    for h, (name, t) in texts.items():
        lines += [f'<a id="{h}"></a>', f"### {h} ({name})", "", "```text", t, "```", ""]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{OUT.name}: {len(pkgs)} crates, {len(texts)} distinct license texts")
    missing = [p["name"] for p, refs in entries if not refs]
    if missing:
        print("no license text found for:", ", ".join(missing))


if __name__ == "__main__":
    main()
